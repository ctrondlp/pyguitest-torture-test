def set_language(language: str) -> None:
    """Set the active language to `language` ("en" or "ja")."""
    global _LANGUAGE
    _LANGUAGE = language if language in ("en", "ja") else "en"


def language() -> str:
    """Return the active language code ("en" or "ja")."""
    return _LANGUAGE


def tr(text: str) -> str:
    """Translate `text` into the active language, falling back to the key."""
    if _LANGUAGE == "ja":
        return _JA.get(text, text)
    return text
